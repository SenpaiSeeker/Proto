function RPCMessageToError(rpcError, request) {
	const message = rpcError.errorMessage;
	let error;
	const ExactCls = require_errors_RPCErrorList.rpcErrorsDict.get(message);
	if (ExactCls) error = new ExactCls({ request });
	else {
		let matched = false;
		for (const [msgRegex, Cls] of require_errors_RPCErrorList.rpcErrorsRe) {
			const m = message.match(msgRegex);
			if (m) {
				error = new Cls({
					request,
					capture: m.length >= 2 ? parseInt(m[1]) : null
				});
				matched = true;
				break;
			}
		}
		if (!matched) error = new ((require_errors_RPCErrorList.baseErrors.get(Math.abs(rpcError.errorCode))) || require_errors_RPCBaseErrors.RPCError)(message, request, rpcError.errorCode);
	}
	error.errorMessage = message;
	return error;
}
